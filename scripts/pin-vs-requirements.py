#!/usr/bin/env python3
"""Regenerate assets/vs/requirements.txt: the VapourSynth stack that "Set up VapourSynth" installs.

Every package is pinned to one version and to the sha256 of its wheel for Linux x86_64, so pip
(run with --require-hashes) refuses anything else, whatever PyPI serves later. Change PINS, run
this script, review the diff, and test a setup before committing. Needs network access to
pypi.org; uses only the standard library.
"""

import json
import sys
import urllib.request
from pathlib import Path

# R81 is what QTGMC and IVTC were checked against; R82 is out but untested here.
# havsfunc is not here on purpose: the one on PyPI (33) needs the old `focus2` plugin and 34 needs
# vsjetpack. vs_setup.rs fetches the last single-file upstream version instead, by commit and sha256.
PINS = {
    "VapourSynth": ("vapoursynth", "81"),
    "vapoursynth-mvtools": ("vapoursynth-mvtools", "29"),
    "vapoursynth-znedi3": ("vapoursynth-znedi3", "3.3"),
    "vapoursynth-vivtc": ("vapoursynth-vivtc", "2.0"),
    "vsutil": ("vsutil", "0.8.0"),
}


def wanted(filename: str) -> bool:
    """The wheel pip would pick on Linux x86_64 with a recent Python (abi3 or pure Python)."""
    if not filename.endswith(".whl"):
        return False
    if filename.endswith("-any.whl"):
        return True
    return "manylinux" in filename and "x86_64" in filename and "cp315" not in filename


def main() -> int:
    lines = [
        "# Generated by scripts/pin-vs-requirements.py. Do not edit by hand.",
        "# Installed with: pip install --require-hashes --only-binary=:all: --no-deps -r requirements.txt",
    ]
    for name, (project, version) in PINS.items():
        url = f"https://pypi.org/pypi/{project}/{version}/json"
        with urllib.request.urlopen(url, timeout=30) as r:
            data = json.load(r)
        files = [u for u in data["urls"] if wanted(u["filename"])]
        if len(files) != 1:
            print(f"{name} {version}: expected one wheel, found {[f['filename'] for f in files]}", file=sys.stderr)
            return 1
        f = files[0]
        lines.append(f"{name}=={version} \\")
        lines.append(f"    --hash=sha256:{f['digests']['sha256']}  # {f['filename']}")
    out = Path(__file__).resolve().parent.parent / "assets/vs/requirements.txt"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
